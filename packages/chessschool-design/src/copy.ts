/** A runner line ("Nice!") in the app language. */
export const phrase = (text: string) => copy.lesson.phrases[text] ?? text;

export function greetingFor(date: Date): string {
  const h = date.getHours();
  if (h < 12) return copy.today.greeting.morning;
  if (h < 18) return copy.today.greeting.afternoon;
  return copy.today.greeting.evening;
}
