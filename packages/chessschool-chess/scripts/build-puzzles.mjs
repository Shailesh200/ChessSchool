#!/usr/bin/env node
// Builds the bundled puzzle pack from the Lichess puzzle database (CC0).
//   node scripts/build-puzzles.mjs [path/to/puzzles.csv.gz]   (from packages/chessschool-chess)
// Default input is the repo's data/chess-school-puzzles.csv.gz (a Lichess export).
// Picks popular, short puzzles spread evenly across ratings, checks every move with chess.js,
// and writes src/puzzles.data.ts.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { gunzipSync } from "node:zlib";
import { Chess } from "chess.js";

const PKG = join(dirname(fileURLToPath(import.meta.url)), "..");
const input = process.argv[2] ?? join(PKG, "../../data/chess-school-puzzles.csv.gz");
const MIN = 400;
const MAX = 2000;
const BUCKET = 100;
const PER_BUCKET = 95;

/** Themes the app offers, in display order. Puzzles keep only these tags. */
const THEMES = ["mateIn1", "mateIn2", "fork", "pin", "skewer", "hangingPiece", "discoveredAttack", "backRankMate", "promotion", "endgame", "defensiveMove", "sacrifice"];

const csv = gunzipSync(readFileSync(input)).toString("utf8").trim().split("\n");
const head = csv.shift().split(",");
const col = Object.fromEntries(head.map((h, i) => [h, i]));

const buckets = new Map();
let checked = 0;
for (const line of csv) {
  const f = line.split(",");
  const rating = Number(f[col.Rating]);
  const moves = f[col.Moves].split(" ");
  const popularity = Number(f[col.Popularity]);
  const plays = Number(f[col.NbPlays]);
  if (rating < MIN || rating >= MAX || moves.length > 6 || moves.length < 2 || popularity < 80 || plays < 150) continue;
  const b = Math.floor(rating / BUCKET);
  const list = buckets.get(b) ?? [];
  if (list.length >= PER_BUCKET * 3) continue;
  // Every move must be legal from the given position.
  const chess = new Chess(f[col.FEN]);
  try {
    for (const u of moves) chess.move({ from: u.slice(0, 2), to: u.slice(2, 4), promotion: u[4] });
  } catch {
    continue;
  }
  checked++;
  const tags = f[col.Themes].split(" ").filter((t) => THEMES.includes(t)).map((t) => THEMES.indexOf(t));
  list.push([f[col.PuzzleId], f[col.FEN], f[col.Moves], rating, tags, popularity * Math.log(plays)]);
  buckets.set(b, list);
}

const pack = [];
for (const [, list] of [...buckets].sort((a, b) => a[0] - b[0])) {
  // Most popular first, but keep a mix of themes.
  list.sort((a, b) => b[5] - a[5]);
  const seen = new Map();
  const picked = [];
  for (const p of list) {
    const key = p[4][0] ?? -1;
    if ((seen.get(key) ?? 0) >= PER_BUCKET / 3) continue;
    seen.set(key, (seen.get(key) ?? 0) + 1);
    picked.push(p);
    if (picked.length >= PER_BUCKET) break;
  }
  for (const p of list) if (picked.length < PER_BUCKET && !picked.includes(p)) picked.push(p);
  pack.push(...picked.map(([id, fen, moves, rating, tags]) => [id, fen, moves, rating, tags]));
}

writeFileSync(
  join(PKG, "src/puzzles.data.ts"),
  `/** Generated by scripts/build-puzzles.mjs from the Lichess puzzle database (CC0) — do not edit. */\n` +
    `export const PUZZLE_THEME_TAGS = ${JSON.stringify(THEMES)} as const;\n` +
    `/** [id, fen, uci moves, rating, theme indexes] */\n` +
    `export const PUZZLE_ROWS: [string, string, string, number, number[]][] = ${JSON.stringify(pack)};\n`,
);
console.log(`puzzles: ${pack.length} bundled from ${checked} checked (${csv.length} in source)`);
