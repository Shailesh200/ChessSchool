#!/usr/bin/env node
// Builds generated piece-set data for @chessschool/chess.
//   pnpm pieces [preview.png]   (from packages/chessschool-chess)
// Every set is drawn as vectors in src/pieceSets*.ts, so this only writes the (empty) PNG table the app imports.
// With a path, it also renders a contact sheet of every set on light and dark squares, for checking new art.
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { PIECE_SETS, pieceArtwork } from "../src/pieceSets.ts";

const PKG = join(dirname(fileURLToPath(import.meta.url)), "..");
const ROOT = join(PKG, "../..");
const HEADER = "/** Generated by scripts/build-piece-sets.mjs — do not edit. */\n";

writeFileSync(
  join(ROOT, "apps/chessschool/lib/pieceAssets.ts"),
  `${HEADER}/** ChessSchool piece sets are drawn as vectors. No bundled PNG sets. */\nexport const PIECE_PNGS: Record<string, number> = {};\n`,
);

const out = process.argv[2];
if (out) {
  const { default: sharp } = await import("sharp");
  const op = (o) => {
    const paint = `fill="${o.fill ?? "none"}" ${o.stroke ? `stroke="${o.stroke}" stroke-width="${o.sw ?? 1}"` : ""} stroke-linejoin="${o.lj ?? "miter"}" stroke-linecap="${o.lc ?? "butt"}"`;
    if (o.t === "path") return `<path d="${o.d}" ${paint}/>`;
    if (o.t === "circle") return `<circle cx="${o.cx}" cy="${o.cy}" r="${o.r}" ${paint}/>`;
    return `<ellipse cx="${o.cx}" cy="${o.cy}" rx="${o.rx}" ry="${o.ry}" ${paint}/>`;
  };
  const S = 72;
  const types = ["p", "n", "b", "r", "q", "k"];
  let svg = "";
  PIECE_SETS.forEach((set, row) => {
    ["w", "b"].forEach((color, half) =>
      types.forEach((type, col) => {
        const x = (half * 6 + col) * S;
        const y = row * S;
        const sq = (half * 6 + col + row) % 2 ? "#8E8BE3" : "#EEEDFF";
        const art = pieceArtwork(set.id, color, type);
        svg += `<rect x="${x}" y="${y}" width="${S}" height="${S}" fill="${sq}"/><svg x="${x + 4}" y="${y + 4}" width="${S - 8}" height="${S - 8}" viewBox="${art.drawing.viewBox}">${art.drawing.ops.map(op).join("")}</svg>`;
      }),
    );
  });
  const W = 12 * S;
  const H = PIECE_SETS.length * S;
  await sharp(Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}">${svg}</svg>`)).png().toFile(out);
  console.log(`preview: ${out}`);
}
