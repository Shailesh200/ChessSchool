#!/usr/bin/env node
// Builds generated piece-set data for @chessschool/chess.
//   node --experimental-strip-types scripts/build-piece-sets.mjs   (from packages/chessschool-chess)
// 1. Retained Lichess sets (Spatial, Arcade, Bold, Heritage, Cartoon, Fantasy) from the 0.3.x app's
//    bundled SVGs -> assets/pieces/<set>/<code>.svg (web) + .png (native) + apps/chessschool/lib/pieceAssets.ts
// 2. ChessSchool Pixel: our own Toy pieces rasterised to a 16x18 grid with outline/shade passes
//    -> src/pieceSets.pixel.ts
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";
import { PIECE_ART } from "../src/pieces.ts";

const PKG = join(dirname(fileURLToPath(import.meta.url)), "..");
const ROOT = join(PKG, "../..");
const HEADER = "/** Generated by scripts/build-piece-sets.mjs — do not edit. */\n";

/* ---------- 1. Retained Lichess sets: original SVG + PNG for native ---------- */
const LICHESS = { spatial: "spatial", arcade: "pixel", bold: "chessnut", heritage: "dubrovny", cartoon: "kiwen-suwi", fantasy: "fantasy" };
const CODES = ["wK", "wQ", "wR", "wB", "wN", "wP", "bK", "bQ", "bR", "bB", "bN", "bP"];
const PNG = 192;
const requires = [];
for (const [id, folder] of Object.entries(LICHESS)) {
  const out = join(PKG, "assets/pieces", id);
  mkdirSync(out, { recursive: true });
  for (const code of CODES) {
    const svg = readFileSync(join(ROOT, "apps/web/public/pieces", folder, `${code}.svg`));
    writeFileSync(join(out, `${code}.svg`), svg);
    // Rasterise at 2x the target from the vector, whatever the file's nominal size.
    const meta = await sharp(svg).metadata();
    const density = Math.max(1, Math.min(2400, (72 * PNG * 2) / Math.max(meta.width ?? PNG, meta.height ?? PNG)));
    await sharp(svg, { density }).resize(PNG, PNG, { fit: "contain", background: { r: 0, g: 0, b: 0, alpha: 0 }, kernel: id === "arcade" ? "nearest" : "lanczos3" }).png({ compressionLevel: 9, palette: true }).toFile(join(out, `${code}.png`));
    requires.push(`  "${id}/${code}": require("@chessschool/chess/assets/pieces/${id}/${code}.png"),`);
  }
}
// Metro only bundles statically required files, so the native app gets a generated map.
writeFileSync(
  join(ROOT, "apps/chessschool/lib/pieceAssets.ts"),
  `${HEADER}export const PIECE_PNGS: Record<string, number> = {\n${requires.join("\n")}\n};\n`,
);
writeFileSync(
  join(PKG, "assets/pieces/ATTRIBUTION.md"),
  `# Retained piece sets\n\nThese six sets come from the Lichess project (https://github.com/lichess-org/lila/tree/master/public/piece) and were bundled in ChessSchool 0.3.x. Licenses differ per set (see Lichess COPYING.md); confirm each before a public store release.\n\n| ChessSchool name | Lichess set |\n|---|---|\n${Object.entries(LICHESS).map(([a, b]) => `| ${a} | ${b} |`).join("\n")}\n`,
);

/* ---------- 2. Pixel set from our Toy art ---------- */
const COLS = 16;
const ROWS = 18;
const COLORS = {
  w: { o: "#2A2547", f: "#FFF7E8", s: "#D9D2F0", h: "#FFFFFF" },
  b: { o: "#15132B", f: "#4A45A0", s: "#34307A", h: "#7E79D6" },
};

async function grid(type) {
  const art = PIECE_ART[type];
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="18 4 64 88" width="${COLS}" height="${ROWS}" preserveAspectRatio="none">${art.body
    .map((d) => `<path d="${d}" fill="#fff" stroke="#fff" stroke-width="3"/>`)
    .join("")}</svg>`;
  const { data } = await sharp(Buffer.from(svg)).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  const on = (x, y) => x >= 0 && y >= 0 && x < COLS && y < ROWS && data[(y * COLS + x) * 4 + 3] > 110;
  const cells = [];
  for (let y = 0; y < ROWS; y++) {
    for (let x = 0; x < COLS; x++) {
      if (!on(x, y)) continue;
      const edge = !on(x - 1, y) || !on(x + 1, y) || !on(x, y - 1) || !on(x, y + 1);
      let k = edge ? "o" : "f";
      if (!edge && (!on(x + 2, y) || !on(x, y + 2))) k = "s";
      if (!edge && (!on(x - 2, y) || !on(x, y - 2)) && k === "f") k = "h";
      cells.push([x, y, k]);
    }
  }
  // Eye for the knight, from the toy art's dot.
  for (const [cx, cy] of art.dots ?? []) {
    const x = Math.floor(((cx - 18) / 64) * COLS);
    const y = Math.floor(((cy - 4) / 88) * ROWS);
    const i = cells.findIndex(([a, b]) => a === x && b === y);
    if (i >= 0) cells[i][2] = "o";
  }
  return cells;
}

const pixel = {};
for (const type of Object.keys(PIECE_ART)) {
  const cells = await grid(type);
  for (const color of ["w", "b"]) {
    const ops = ["o", "f", "s", "h"]
      .map((k) => ({ k, d: cells.filter((c) => c[2] === k).map(([x, y]) => `M${x} ${y}h1v1h-1z`).join("") }))
      .filter((p) => p.d)
      .map(({ k, d }) => ({ t: "path", d, fill: COLORS[color][k] }));
    pixel[`${color}${type.toUpperCase()}`] = { viewBox: `0 0 ${COLS} ${ROWS}`, ops };
  }
}
writeFileSync(
  join(PKG, "src/pieceSets.pixel.ts"),
  `${HEADER}import type { PieceDrawing } from "./pieceSets";\n\nexport const PIXEL_SET: Record<string, PieceDrawing> = ${JSON.stringify(pixel)};\n`,
);
console.log(`piece sets: ${Object.keys(LICHESS).length} retained (svg + png) + pixel (${Object.keys(pixel).length} sprites)`);
