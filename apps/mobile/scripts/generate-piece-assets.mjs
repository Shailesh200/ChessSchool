#!/usr/bin/env node
/**
 * Bundle Lichess piece SVGs from apps/web/public/pieces into a TS module
 * so mobile renders pieces offline (production may not expose /pieces/*).
 *
 * Normalizes SVGs for react-native-svg: inlines <style> classes, strips
 * Inkscape clip-path hacks (kiwen-suwi), ensures viewBox.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "../../..");
const SRC = path.join(ROOT, "apps/web/public/pieces");
const OUT = path.join(ROOT, "apps/mobile/src/pieceSvgContent.ts");

const SETS = [
  "cburnett",
  "merida",
  "alpha",
  "spatial",
  "pixel",
  "dubrovny",
  "chessnut",
  "kiwen-suwi",
  "fairytale",
  "anime",
  "fantasy",
];

const CODES = ["wK", "wQ", "wR", "wB", "wN", "wP", "bK", "bQ", "bR", "bB", "bN", "bP"];

/** Parse `.className{prop:val;...}` rules from a <style> block. */
function parseClassRules(cssText) {
  const rules = new Map();
  for (const m of cssText.matchAll(/\.([a-zA-Z0-9_-]+)\s*\{([^}]*)\}/g)) {
    rules.set(m[1], m[2].replace(/\s+/g, " ").trim());
  }
  return rules;
}

/** Bake stylesheet classes into element style="" so SvgXml can render them. */
function inlineSvgStyles(svg) {
  const styleMatch = svg.match(/<style[^>]*>([\s\S]*?)<\/style>/i);
  if (!styleMatch) return svg;

  const rules = parseClassRules(styleMatch[1]);
  if (rules.size === 0) return svg.replace(styleMatch[0], "");

  let out = svg.replace(styleMatch[0], "");
  out = out.replace(/<([a-zA-Z][\w:-]*)([^>]*?)(\/?)>/g, (full, tag, attrs, selfClose) => {
    const classMatch = attrs.match(/\sclass="([^"]+)"/);
    if (!classMatch) return full;

    const fromClass = classMatch[1]
      .split(/\s+/)
      .map((c) => rules.get(c))
      .filter(Boolean)
      .join(";");

    let nextAttrs = attrs.replace(/\sclass="[^"]+"/, "");
    const styleMatch = nextAttrs.match(/\sstyle="([^"]*)"/);
    if (styleMatch) {
      const merged = [fromClass, styleMatch[1]].filter(Boolean).join(";");
      nextAttrs = nextAttrs.replace(/\sstyle="[^"]*"/, ` style="${merged}"`);
    } else if (fromClass) {
      nextAttrs += ` style="${fromClass}"`;
    }

    return `<${tag}${nextAttrs}${selfClose}>`;
  });
  return out;
}

/** Kiwen-suwi uses off-canvas clip paths; RN clip-path url() often renders blank. */
function normalizeKiwenSuwi(svg) {
  return svg
    .replace(/<defs>\s*<clipPath[^>]*>[\s\S]*?<\/clipPath>\s*<\/defs>/gi, "")
    .replace(/\sclip-path="url\([^"]+\)"/gi, "")
    .replace(/\soverflow="hidden"/gi, "");
}

function ensureViewBox(svg) {
  if (/viewBox=/i.test(svg)) return svg;
  const w = svg.match(/\bwidth="(\d+(?:\.\d+)?)/);
  const h = svg.match(/\bheight="(\d+(?:\.\d+)?)/);
  if (!w || !h) return svg;
  return svg.replace(/<svg\b/, `<svg viewBox="0 0 ${w[1]} ${h[1]}"`);
}

function normalizePieceSvg(set, svg) {
  let out = svg.trim();
  if (set === "kiwen-suwi") out = normalizeKiwenSuwi(out);
  out = inlineSvgStyles(out);
  out = ensureViewBox(out);
  return out;
}

const map = {};
let missing = 0;

for (const set of SETS) {
  map[set] = {};
  for (const code of CODES) {
    const file = path.join(SRC, set, `${code}.svg`);
    if (!fs.existsSync(file)) {
      console.warn(`missing: ${set}/${code}.svg`);
      missing++;
      continue;
    }
    const raw = fs.readFileSync(file, "utf8").trim();
    map[set][code] = normalizePieceSvg(set, raw);
  }
}

if (missing > 0) {
  console.error(`Abort: ${missing} piece SVG(s) missing under ${SRC}`);
  process.exit(1);
}

const header = `/** Auto-generated by scripts/generate-piece-assets.mjs — do not edit. */\n\n`;
const body = `export const PIECE_SVG: Record<string, Record<string, string>> = ${JSON.stringify(map, null, 2)};\n\nexport function getPieceSvg(set: string, code: string): string | null {\n  return PIECE_SVG[set]?.[code] ?? null;\n}\n`;

fs.writeFileSync(OUT, header + body);
console.log(`Wrote ${OUT} (${SETS.length} sets × ${CODES.length} pieces)`);
